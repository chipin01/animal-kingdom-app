// Helper to wrap wikimedia url in weserv proxy for 100% reliability
function wikiImg(pathName) {
  const base = "https://upload.wikimedia.org/wikipedia/commons/" + pathName;
  return "https://images.weserv.nl/?url=" + encodeURIComponent(base) + "&w=500&output=jpg";
}

